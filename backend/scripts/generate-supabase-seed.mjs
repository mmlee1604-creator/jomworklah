import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { interests, jobs, personas, skills } from '../src/db/seed-data.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const quote = value => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
};

function insert(table, columns, rows, conflictColumns, updates = columns.filter(column => !conflictColumns.includes(column))) {
  if (!rows.length) return '';
  const values = rows.map(row => `(${row.map(quote).join(', ')})`).join(',\n  ');
  const conflict = updates.length
    ? `DO UPDATE SET ${updates.map(column => `${column} = EXCLUDED.${column}`).join(', ')}`
    : 'DO NOTHING';
  return `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n  ${values}\nON CONFLICT (${conflictColumns.join(', ')}) ${conflict};`;
}

const statements = [
  '-- Generated by `npm run supabase:seed:generate` from src/db/seed-data.js.',
  '-- Apply after app-schema.sql. Safe to re-run for the built-in reference/demo data.',
  'BEGIN;',
  insert('skills', ['id', 'name', 'category', 'description'],
    skills.map(({ id, name, category, description }) => [id, name, category, description]), ['id']),
  insert('interests', ['id', 'label'], interests.map(({ id, label }) => [id, label]), ['id']),
  insert('jobs', ['id', 'title', 'category', 'sector', 'icon', 'summary', 'qualification'],
    jobs.map(({ id, title, category, sector, icon, summary, qualification }) =>
      [id, title, category, sector, icon, summary, qualification]), ['id']),
  insert('job_requirements', ['job_id', 'skill_id', 'level', 'weight'],
    jobs.flatMap(job => job.requirements.map(({ skillId, level, weight }) => [job.id, skillId, level, weight])),
    ['job_id', 'skill_id']),
  insert('job_tags', ['job_id', 'interest_id'],
    jobs.flatMap(job => job.tags.map(interestId => [job.id, interestId])), ['job_id', 'interest_id']),
  insert('job_responsibilities', ['job_id', 'position', 'text'],
    jobs.flatMap(job => job.responsibilities.map((text, position) => [job.id, position, text])),
    ['job_id', 'position']),
  insert('job_progression', ['job_id', 'position', 'title'],
    jobs.flatMap(job => job.progression.map((title, position) => [job.id, position, title])),
    ['job_id', 'position']),
  insert('job_projects', ['job_id', 'position', 'brief'],
    jobs.flatMap(job => job.project.map((brief, position) => [job.id, position, brief])),
    ['job_id', 'position']),
  `DELETE FROM profile_skills
WHERE user_id IN (SELECT id FROM users WHERE kind = 'demo_template');
DELETE FROM profile_interests
WHERE user_id IN (SELECT id FROM users WHERE kind = 'demo_template');`,
  insert('users', ['id', 'kind', 'persona_key'],
    Object.values(personas).map(persona => [`tpl_${persona.key}`, 'demo_template', persona.key]), ['id'],
    ['kind', 'persona_key']),
  insert('profiles',
    ['user_id', 'name', 'headline', 'qualification', 'field_of_study', 'location', 'experience',
      'projects', 'budget', 'weekly_hours', 'learning_mode'],
    Object.values(personas).map(persona => [
      `tpl_${persona.key}`, persona.name, persona.headline, persona.qualification, persona.fieldOfStudy,
      persona.location, persona.experience, persona.projects, persona.budget, persona.weeklyHours,
      persona.learningMode
    ]),
    ['user_id'],
    ['name', 'headline', 'qualification', 'field_of_study', 'location', 'experience', 'projects',
      'budget', 'weekly_hours', 'learning_mode']),
  insert('journeys', ['user_id', 'started', 'target_job_id'],
    Object.values(personas).map(persona => [`tpl_${persona.key}`, 1, persona.targetJobId]),
    ['user_id'], ['started', 'target_job_id']),
  insert('profile_skills', ['user_id', 'skill_id', 'evidence_level'],
    Object.values(personas).flatMap(persona =>
      Object.entries(persona.scores).map(([skillId, level]) => [`tpl_${persona.key}`, skillId, level])),
    ['user_id', 'skill_id'], ['evidence_level']),
  insert('profile_interests', ['user_id', 'interest_id'],
    Object.values(personas).flatMap(persona =>
      persona.interests.map(interestId => [`tpl_${persona.key}`, interestId])),
    ['user_id', 'interest_id'], []),
  'COMMIT;'
].filter(Boolean);

const output = path.join(root, 'supabase', 'seed.sql');
fs.writeFileSync(output, `${statements.join('\n\n')}\n`);
console.log(`Wrote ${path.relative(root, output)}`);
